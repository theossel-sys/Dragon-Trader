#!/usr/bin/env python3
"""gen_scheme.py <games.cfg> <game id> <out dir>

Reads the game's line of apps/launcher/games.cfg (RetroStone Arcade's touch schemes) and writes
<out dir>/web_scheme.h (the zones for rs_web.c) and <out dir>/web_buttons.json (the drawn buttons for the page).
A game without a line uses "default". Games that read touches themselves (rs_game.touch_native) ignore the zones.
"""
import json
import sys

BTN = {"A": "RS_BTN_A", "B": "RS_BTN_B", "X": "RS_BTN_X", "Y": "RS_BTN_Y", "L": "RS_BTN_L", "R": "RS_BTN_R",
       "UP": "RS_BTN_UP", "DOWN": "RS_BTN_DOWN", "LEFT": "RS_BTN_LEFT", "RIGHT": "RS_BTN_RIGHT",
       "START": "RS_BTN_START", "SELECT": "RS_BTN_SELECT"}
NAMED = {"all": (0, 0, 100, 100), "left": (0, 0, 50, 100), "right": (50, 0, 100, 100),
         "top": (0, 0, 100, 50), "bottom": (0, 50, 100, 100)}
ARROWS = {"UP": "↑", "DOWN": "↓", "LEFT": "←", "RIGHT": "→"}


def entries(path):
    out = {}
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].split()
        if line:
            out[line[0]] = line[1:]
    return out


def main():
    cfg, game, out = sys.argv[1:4]
    e = entries(cfg)
    keys = e.get(game, e["default"])
    zones, buttons, pause = [], [], "START"
    for kv in keys:
        k, _, v = kv.partition("=")
        if k == "pause":
            pause = v
        if k not in ("touch", "button"):
            continue
        where, _, what = v.rpartition(":")
        what, _, icon = what.partition("@")
        rect = NAMED.get(where) or tuple(int(n) for n in where.split(","))
        bits = " | ".join(BTN[b] for b in what.split("+"))
        zones.append("{%d, %d, %d, %d, %s}" % (rect + (bits,)))
        if k == "button":
            first = what.split("+")[0]
            label = {"up": "↑", "down": "↓", "left": "←", "right": "→",
                     "shot": "➶"}.get(icon) or ARROWS.get(first) or first
            buttons.append({"r": rect, "t": label})
    with open(out + "/web_scheme.h", "w") as f:
        f.write("/* generated by gen_scheme.py from games.cfg (%s) */\n" % game)
        f.write("#define WEB_NZONES %d\n" % len(zones))
        f.write("#define WEB_ZONES {%s}\n" % (", ".join(zones) or "{0, 0, 0, 0, 0}"))
        f.write("#define WEB_PAUSE %s\n" % BTN[pause])
    with open(out + "/web_buttons.json", "w") as f:
        json.dump(buttons, f, ensure_ascii=False)


if __name__ == "__main__":
    main()
